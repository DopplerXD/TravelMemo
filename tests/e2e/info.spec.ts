import { test, expect } from '@playwright/test';

test('Info navigation, themes, narrow screens and administrator editing', async ({ page, request }, info) => {
  test.setTimeout(120000);
  const initial = await (await request.get('/api/profile')).json();
  await page.emulateMedia({ colorScheme: 'light' });
  await page.goto('/stats');
  const canvas = await page.locator('.maplibregl-canvas').elementHandle();
  const nav = page.getByRole('navigation', { name: '主导航' });
  await expect(nav.getByRole('button').filter({ hasText: /^(Trips|Places|Timeline|Stats|Info)$/ })).toHaveText(['Trips', 'Places', 'Timeline', 'Stats', 'Info']);
  await nav.getByRole('button', { name: 'Info', exact: true }).click();
  await expect(page).toHaveURL(/\/info$/);
  expect(await canvas!.evaluate(element => element.isConnected)).toBeTruthy();
  const panel = page.getByRole('region', { name: '个人信息', exact: true });
  await expect(panel).toContainText(initial.name);
  await expect(panel.getByRole('link', { name: initial.blog, exact: true })).toHaveAttribute('rel', 'noopener noreferrer');
  await page.getByRole('button', { name: /切换.*暗色/ }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(panel).toContainText(initial.school);
  await page.screenshot({ path: `.artifacts/${info.project.name}-info-dark.png` });
  await page.setViewportSize({ width: 320, height: 700 });
  const rect = await nav.boundingBox();
  expect(rect!.x).toBeGreaterThanOrEqual(0);
  expect(rect!.x + rect!.width).toBeLessThanOrEqual(320);
  expect(rect!.y + rect!.height).toBeLessThanOrEqual(700);
  expect(await nav.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy();
  await expect(nav.getByRole('button', { name: '返回地图', exact: true })).toBeVisible();
  await page.screenshot({ path: `.artifacts/${info.project.name}-info-320.png` });
  await nav.getByRole('button', { name: '返回地图', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.goto('/admin');
  await page.getByLabel('账号', { exact: true }).fill('e2e-admin');
  await page.getByLabel('密码', { exact: true }).fill('e2e-only-password-2026');
  await page.getByRole('button', { name: '登录管理后台', exact: true }).click();
  await page.getByRole('button', { name: '个人信息', exact: true }).click();
  const editor = page.getByRole('form', { name: '编辑个人信息' });
  await expect(editor.getByLabel('Name', { exact: true })).toHaveValue(initial.name);
  await editor.getByLabel('Name', { exact: true }).fill(`${info.project.name} Doppler`);
  await editor.getByRole('button', { name: '保存个人信息' }).click();
  await expect(page.getByRole('status')).toContainText('个人信息已保存');
  await page.goto('/info');
  await expect(panel).toContainText(`${info.project.name} Doppler`);
  await page.goBack();
  await expect(page).toHaveURL(/\/admin$/);
  const login = await request.post('/api/login', { data: { username: 'e2e-admin', password: 'e2e-only-password-2026' } });
  await request.put('/api/profile', { data: initial, headers: { 'X-CSRF-Token': (await login.json()).csrfToken } });
});
