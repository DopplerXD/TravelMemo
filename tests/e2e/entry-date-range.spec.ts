import { test, expect } from '@playwright/test';

test('旧简记起止同日、编辑跨年区间并在公开视图展示', async ({ page, request }, info) => {
  test.setTimeout(90000);
  const login = await request.post('/api/login', { data: { username: 'e2e-admin', password: 'e2e-only-password-2026' } });
  const headers = { 'X-CSRF-Token': (await login.json()).csrfToken };
  const create = async (collection: string, data: unknown) => {
    const response = await request.post(`/api/${collection}`, { data, headers });
    expect(response.status()).toBe(201);
    return response.json();
  };
  const place = await create('places', { name: `${info.project.name}区间南京`, province: '江苏省', provinceCode: '320000', city: '南京市', cityCode: '320100', lng: 118.79, lat: 32.06 });
  const trip = await create('trips', { title: `${info.project.name}跨年旅行`, description: '', cityRoute: [] });
  const entry = await create('entries', { title: `${info.project.name}跨年简记`, date: '2026-12-31', placeId: place.id, tripId: trip.id, body: '两年的交界', photos: [] });
  expect(entry.endDate).toBe('2026-12-31');
  await page.goto('/admin');
  await page.getByLabel('账号', { exact: true }).fill('e2e-admin');
  await page.getByLabel('密码', { exact: true }).fill('e2e-only-password-2026');
  await page.getByRole('button', { name: '登录管理后台' }).click();
  await page.getByRole('button', { name: '新建简记', exact: true }).click();
  let dialog = page.getByRole('dialog');
  const start = dialog.getByLabel('开始日期', { exact: false });
  const end = dialog.getByLabel('结束日期', { exact: false });
  expect(await start.inputValue()).toBe(await end.inputValue());
  await start.fill('2026-10-21');
  await expect(end).toHaveValue('2026-10-21');
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await page.locator('.admin-row').filter({ hasText: entry.title }).getByRole('button', { name: '编辑', exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('开始日期', { exact: false })).toHaveValue('2026-12-31');
  await expect(dialog.getByLabel('结束日期', { exact: false })).toHaveValue('2026-12-31');
  await dialog.getByLabel('结束日期', { exact: false }).fill('2026-12-30');
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(dialog).toContainText('结束日期不能早于开始日期');
  await dialog.getByLabel('结束日期', { exact: false }).fill('2027-01-02');
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const stored = await (await request.get(`/api/entries/${entry.id}`)).json();
  expect(stored.date).toBe('2026-12-31');
  expect(stored.endDate).toBe('2027-01-02');
  const range = '2026年12月31日 – 2027年1月2日';
  await expect(page.locator('.admin-row').filter({ hasText: entry.title })).toContainText(range);
  await page.goto('/timeline');
  const card = page.getByRole('button', { name: `查看简记 ${entry.title}`, exact: true });
  await expect(card).toContainText(range, { timeout: 15000 });
  await expect(page.getByLabel('按年份筛选')).not.toContainText('2027');
  await card.click();
  await expect(page.getByRole('region', { name: '简记详情' })).toContainText(range);
  await page.getByRole('button', { name: '关闭简记详情' }).click();
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: 'Trips', exact: true }).click();
  const tripCard = page.getByRole('button', { name: `打开旅行 ${trip.title}`, exact: true });
  await expect(tripCard).toContainText(range);
  await tripCard.click();
  await expect(page.getByRole('region', { name: '旅行详情' })).toContainText(range);
  await page.screenshot({ path: `.artifacts/${info.project.name}-date-range.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
});
